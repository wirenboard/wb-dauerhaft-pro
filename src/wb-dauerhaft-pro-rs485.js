/* =============================================================================
 * БЛОК HOT-RELOAD: УПРАВЛЕНИЕ СОСТОЯНИЕМ ДРАЙВЕРА ПРИ ПЕРЕЗАГРУЗКАХ СКРИПТА
 * =============================================================================
 *
 * Проблема: wb-rules допускает многократный запуск одного и того же скрипта
 * (hot-reload при редактировании, перезапуск wb-rules и т.д.). Каждый запуск
 * создаёт новые таймеры и MQTT-подписки, а старые продолжают висеть в памяти,
 * вызывая дублирующиеся действия и утечку ресурсов.
 *
 * Решение — механизм поколений (__DP_GEN):
 *   1. Объект __DP_DauerhaftPro_State хранится в глобальном пространстве имён
 *      и переживает hot-reload.
 *   2. При каждом запуске скрипта поколение gen увеличивается на 1.
 *   3. __DP_GEN фиксирует текущее поколение в начале запуска.
 *   4. Все MQTT-обработчики и таймеры начинают работу с проверки:
 *      if (__DP_GEN !== __DP_STATE.gen) return;
 *      Это позволяет «заглушить» старые колбэки без удаления из движка.
 *   5. Старые таймеры и подписки принудительно останавливаются/отменяются
 *      перед инициализацией нового поколения.
 * =============================================================================
 */

/*
 * __root — ссылка на глобальный объект среды выполнения.
 * В wb-rules/Duktape это обычно this или global.
 * Используется для хранения __DP_DauerhaftPro_State между перезапусками.
 */
var __root = (typeof global !== "undefined") ? global : ((typeof window !== "undefined") ? window : this);

/*
 * __DP_STATE — единый объект состояния драйвера, переживающий hot-reload.
 * Поля:
 *   gen     {number}  — счётчик поколений, увеличивается при каждом запуске.
 *   tickers {object}  — словарь имён таймеров, запущенных текущим поколением.
 *                        Используется для остановки таймеров при следующем запуске.
 *   subs    {object}  — словарь дескрипторов MQTT-подписок текущего поколения.
 *                        Используется для отписки при следующем запуске.
 */
var __DP_STATE = __root.__DP_DauerhaftPro_State;
if (!__DP_STATE) {
    __DP_STATE = { gen: 0, tickers: {}, subs: {} };
    __root.__DP_DauerhaftPro_State = __DP_STATE;
}

/* --- ОЧИСТКА РЕСУРСОВ ПРЕДЫДУЩЕГО ЗАПУСКА И ПОДГОТОВКА НОВОГО ПОКОЛЕНИЯ ---
 *
 * Останавливаем таймеры и отменяем MQTT-подписки предыдущего поколения.
 * После этого сбрасываем хранилища и увеличиваем счётчик поколений.
 * Ошибки игнорируются: при первом запуске словари пусты.
 */
try {
    for (var t in __DP_STATE.tickers) { try { stopTicker(t); } catch (e) { } }
    for (var k in __DP_STATE.subs) { try { untrackMqtt(__DP_STATE.subs[k]); } catch (e) { } }
} catch (e) { }
__DP_STATE.tickers = {};
__DP_STATE.subs = {};
__DP_STATE.gen = (__DP_STATE.gen || 0) + 1;

/*
 * __DP_GEN — локальная константа текущего поколения.
 * Все асинхронные обработчики сравнивают её с __DP_STATE.gen:
 * если значения расходятся — скрипт был перезапущен, обработчик устарел.
 */
var __DP_GEN = __DP_STATE.gen;

/* =============================================================================
 * ГЛОБАЛЬНЫЕ РЕЕСТРЫ ДЛЯ ЕДИНОГО ДИСПЕТЧЕРА
 * =============================================================================
 *
 * devicePortParams {object}
 *   Ключ: имя устройства (NameBlind, строка).
 *   Значение: объект { port, speed, parity, stopBit }.
 *   Заполняется при каждом вызове createBlind() и используется функцией
 *   _dp_dispatchSingleDevice(), чтобы отправить команду в нужный порт без
 *   хранения параметров в замыкании.
 *
 * singleDeviceTopics {Array<string>}
 *   Список путей контролов вида "ИмяУстройства/ИмяКонтрола".
 *   Это не MQTT-топики, а строки для whenChanged правила wb-rules.
 *   Заполняется при каждом createBlind() и передаётся в whenChanged единого
 *   правила dauerhaftpro_single_dispatcher.
 *
 * Оба объекта сбрасываются при каждом запуске скрипта (hot-reload):
 * они не должны накапливать записи из предыдущих поколений.
 * =============================================================================
 */
var devicePortParams = {};
var singleDeviceTopics = [];

/* Принудительный сброс: при первом запуске try-блоки ничего не делают,
 * при hot-reload — гарантируют чистое состояние, даже если предыдущие
 * присвоения выше каким-то образом не отработали (защита от будущих ошибок). */
try { devicePortParams = {}; } catch(e) {}
try { singleDeviceTopics = []; } catch(e) {}


/* =============================================================================
 * УТИЛИТА ДЛЯ ПЕРЕЗАПУСКА ТАЙМЕРОВ (restartTicker)
 * =============================================================================
 * Если wb-rules уже предоставляет глобальную restartTicker — используем её.
 * Иначе определяем свою реализацию: сначала безопасно останавливаем старый
 * таймер, затем запускаем новый.
 *
 * Параметры:
 *   name     {string} — уникальное имя таймера.
 *   interval {number} — интервал срабатывания в миллисекундах.
 * =============================================================================
 */
var restartTicker = (typeof restartTicker === 'function') ? restartTicker : function (name, interval) {
    try { stopTicker(name); } catch (e) { }
    try { startTicker(name, interval); } catch (e) { }
};


/* =============================================================================
 * ФУНКЦИЯ ПЕРЕЗАПУСКА ТАЙМЕРА С ОТСЛЕЖИВАНИЕМ (restartTickerTracked)
 * =============================================================================
 * Обёртка над restartTicker, которая дополнительно регистрирует таймер
 * в __DP_STATE.tickers. Это позволяет при следующем hot-reload автоматически
 * остановить все таймеры текущего поколения.
 *
 * Параметры:
 *   name     {string} — уникальное имя таймера.
 *   interval {number} — интервал срабатывания в миллисекундах.
 * =============================================================================
 */
function restartTickerTracked(name, interval) {
    restartTicker(name, interval);
    __DP_STATE.tickers[name] = true;
}


/* =============================================================================
 * ГЛОБАЛЬНАЯ ОБРАБОТКА MQTT-ОТВЕТОВ
 * =============================================================================
 *
 * _mqttKeyToDevice {object}
 *   Маппинг: полный MQTT-топик ответа → имя виртуального устройства (строка).
 *   Ключ: строка вида "/rpc/v1/wb-mqtt-serial/port/Load/ИмяУстройства/reply".
 *   Значение: строка NameBlind.
 *   Позволяет _dp_globalMqttRouter за O(1) определить, какому устройству
 *   принадлежит входящий MQTT-ответ.
 *
 * Архитектурная заметка (v1.14 vs v1.13):
 *   В v1.13 для каждого устройства создавалась отдельная анонимная
 *   callback-функция через замыкание внутри trackMqttSafe. Duktape создавал
 *   новый heap-объект (~175 байт) для каждого такого замыкания. При N
 *   устройствах и частых hot-reload это приводило к росту heap.
 *   В v1.14 используется единая именованная функция _dp_globalMqttRouter,
 *   которая создаётся один раз и переиспользуется для всех подписок.
 * =============================================================================
 */
var _mqttKeyToDevice = {};

/*
 * _dp_globalMqttRouter(message)
 * -------------------------------------------------------------------------
 * Единый маршрутизатор MQTT-ответов от всех приводов.
 *
 * Именованная функция верхнего уровня: Duktape не выделяет новый heap-объект
 * при её передаче в trackMqtt. Одно определение на весь драйвер.
 *
 * Алгоритм:
 *   1. Проверяем актуальность поколения (__DP_GEN === __DP_STATE.gen).
 *      Если скрипт был перезапущен, но старый обработчик ещё вызывается
 *      движком — выходим немедленно.
 *   2. Извлекаем topicPath из объекта сообщения.
 *   3. За O(1) находим имя устройства в _mqttKeyToDevice.
 *   4. Передаём управление _dp_handleDeviceReply().
 *
 * Параметры:
 *   message {object} — MQTT-сообщение wb-rules: { topicPath, topic, value, ... }
 */
function _dp_globalMqttRouter(message) {
    if (__DP_GEN !== __DP_STATE.gen) return;
    // O(1)-доступ: топик входящего сообщения → имя устройства.
    var topic = message.topicPath || message.topic || '';
    var name = _mqttKeyToDevice[topic];
    if (!name) return;
    _dp_handleDeviceReply(name, message);
}

/*
 * _dp_handleDeviceReply(NameBlind, message)
 * -------------------------------------------------------------------------
 * Обрабатывает JSON-ответ от wb-mqtt-serial RPC для конкретного устройства.
 * Вынесена из createBlind в v1.14: не является замыканием, не хранит
 * ссылки на локальный контекст createBlind(), что устраняет удержание
 * памяти.
 *
 * Порядок обработки:
 *   1. Парсим JSON.
 *   2. Сбрасываем флаги inFlight по requestID (850/513/514/515).
 *   3. Обрабатываем ответ на запрос адреса (id=903).
 *   4. Обрабатываем ping (id=850): проверяем CRC, адрес, обновляем онлайн-статус.
 *      После ping — ранний return: ping не нужно разбирать как данные устройства.
 *   5. Для остальных id: проверяем отсутствие ошибок, затем вызываем handleReply().
 *
 * Параметры:
 *   NameBlind {string} — имя виртуального устройства (совпадает с ключом в реестрах).
 *   message   {object} — MQTT-сообщение с полем value (JSON-строка RPC-ответа).
 */
function _dp_handleDeviceReply(NameBlind, message) {
    var replyObj;
    try { replyObj = JSON.parse(message.value); } catch (e) { return; }
    if (!replyObj) return;

    // --- Сброс флагов выполнения при любом ответе с нашим ID ---
    // pollState[NameBlind] хранит состояние инфлайт-запросов для каждого типа опроса.
    // Сбрасываем соответствующий флаг, чтобы следующий тик мог отправить новый запрос.
    var st = pollState[NameBlind];
    if (st) {
        if (replyObj.id === 850) st.ping.inFlight = false;
        else if (replyObj.id === 513) st.pos.inFlight = false;
        else if (replyObj.id === 514) st.angle.inFlight = false;
        else if (replyObj.id === 515) st.sw.inFlight = false;
    }

    // --- Обработка ответа на запрос адреса (id=903) ---
    // Согласно разделу 3.2 протокола «Профкарниз Dauerhaft PRO RS-485 v2.3»,
    // ответ на запрос адреса (подкоманда 0x01) содержит адрес устройства в байте 4.
    // Здесь мы извлекаем его из hex-строки ответа и сравниваем с ожидаемым (поле Hex).
    if (replyObj.id === 903 && replyObj.result && replyObj.result.response) {
        var hexOnly3 = String(replyObj.result.response).replace(/[^0-9a-fA-F]/g, '').toUpperCase();
        if (hexOnly3.length >= 2) {
            var addrHex3 = hexOnly3.substr(0, 2);
            var hxWanted = String(dev[NameBlind + '/Hex'] || '').trim().toUpperCase();
            if (hxWanted && addrHex3 === hxWanted) {
                dev[NameBlind + "/Адрес устройства"] = addrHex3;
                blindAddr[NameBlind] = parseInt(addrHex3, 16) & 0xFF;
            }
        }
    }

    // --- Обработка пинга (id=850) ---
    // Ping — это фактически запрос адреса устройства (функция 0x01, подкоманда 0x01,
    // раздел 3.2 протокола «Профкарниз Dauerhaft PRO RS-485 v2.3»).
    // Если ответ содержит корректный CRC и первый байт совпадает с ожидаемым адресом,
    // устройство считается онлайн. После ping обязателен ранний return:
    // ответ на ping не нужно разбирать как данные (позицию, угол и т.д.).
    if (replyObj.id === 850) {
        if (replyObj.result && replyObj.result.response) {
            var rawHexStrPing = replyObj.result.response;
            var hxPing = normalizeHex(rawHexStrPing).toUpperCase();
            if (checkCrc16ModbusFast(hxPing)) {
                var first = hxPing.substr(0, 2);
                var hxTarget = String(dev[NameBlind + '/Hex'] || '').trim().toUpperCase();
                if (hxTarget && first === hxTarget) {
                    onlineFlag[NameBlind] = true;
                    dev[NameBlind + '/Состояние'] = 'В СЕТИ';
                    lastSeenTs[NameBlind] = now();
                    DRIVER_REGISTRY.updateActivity(NameBlind);
                }
            }
        }
        return; // ping полностью обработан — не передавать в handleReply
    }

    // Если RPC вернул ошибку — игнорируем ответ
    if (replyObj.error !== null && replyObj.error !== undefined) return;

    // --- Обработка данных устройства (позиция, угол, версия ПО) ---
    if (replyObj.result && replyObj.result.response) {
        var rawHexStr = replyObj.result.response;
        var hexStr = normalizeHex(rawHexStr);
        if (hexStr.length < 2) return;
        var addrByte = getByteAt(hexStr, 0) & 0xFF;

        // Сравниваем адрес в ответе с ожидаемым (поле Hex).
        // Если совпадает — обновляем временную метку и онлайн-статус.
        var tgt = getHexAddrStrict(NameBlind);
        if (tgt !== null && addrByte === tgt) {
            lastSeenTs[NameBlind] = now();
            if (!onlineFlag[NameBlind]) setOnline(NameBlind, true);
            else DRIVER_REGISTRY.updateActivity(NameBlind);
        }

        // Для служебных запросов (901/902/903) не проверяем lastReqAddr:
        // ответы на адресные команды могут прийти с любым адресом.
        if (replyObj.id !== 901 && replyObj.id !== 902 && replyObj.id !== 903) {
            var exp = (lastReqAddr[NameBlind] !== undefined) ? (lastReqAddr[NameBlind] & 0xFF) : null;
            if (exp !== null && addrByte !== exp) return;
        }
        handleReply(NameBlind, rawHexStr);
    }
}

/*
 * trackMqttSafe(key, topic, deviceName)
 * -------------------------------------------------------------------------
 * Безопасная подписка на MQTT-топик ответов конкретного устройства.
 *
 * В v1.14 функция принимает имя устройства (строку), а не функцию-замыкание.
 * Подписка выполняется через единую именованную функцию _dp_globalMqttRouter,
 * которая маршрутизирует ответы по _mqttKeyToDevice.
 *
 * Параметры:
 *   key        {string} — служебный ключ подписки для __DP_STATE.subs.
 *                          Формат: NameBlind + "_reply".
 *   topic      {string} — полный MQTT-топик для подписки (reply-топик).
 *   deviceName {string} — имя виртуального устройства (NameBlind).
 *
 * Возвращает: дескриптор подписки (результат trackMqtt).
 */
function trackMqttSafe(key, topic, deviceName) {
    // Отписываемся от предыдущей подписки по этому ключу, если она существует.
    // Это нужно для корректного hot-reload: при повторном вызове createBlind()
    // старая подписка должна быть снята до создания новой.
    try {
        if (__DP_STATE.subs[key]) {
            untrackMqtt(__DP_STATE.subs[key]);
            __DP_STATE.subs[key] = null;
        }
    } catch (e) {}

    // Сохраняем маппинг: полный топик → имя устройства (O(1)-доступ в роутере).
    // В v1.13 был обратный маппинг (deviceName → cb), что требовало O(N)-перебора.
    _mqttKeyToDevice[topic] = deviceName;

    // Подписываемся с именованной функцией — без создания нового замыкания.
    // _dp_globalMqttRouter — единый обработчик для всех устройств.
    var h = trackMqtt(topic, _dp_globalMqttRouter);
    __DP_STATE.subs[key] = h;
    return h;
}


/* =============================================================================
 * БЕЗОПАСНОЕ ДОБАВЛЕНИЕ КОНТРОЛА В ВИРТУАЛЬНОЕ УСТРОЙСТВО (addControlSafe)
 * =============================================================================
 * Добавляет контрол в виртуальное устройство, только если он ещё не существует.
 * Обеспечивает идемпотентность: повторный вызов createBlind() при hot-reload
 * не создаёт дублирующихся контролов и не вызывает исключений.
 *
 * Параметры:
 *   vd   {object} — виртуальное устройство wb-rules (результат getDevice).
 *   name {string} — имя контрола.
 *   spec {object} — спецификация контрола: { type, value, min, max, readonly }.
 * =============================================================================
 */
function addControlSafe(vd, name, spec) {
    if (!vd) return;
    try {
        if (typeof vd.isControlExists === 'function' && vd.isControlExists(name)) return;
        if (typeof vd.addControl === 'function') {
            vd.addControl(name, spec);
        }
    } catch (e) {
    }
}

/* =============================================================================
 * ОБРАБОТЧИК НАЖАТИЯ НА КНОПКУ (onPush)
 * =============================================================================
 * Выполняет две задачи при нажатии кнопки типа 'pushbutton':
 *   1. Проверяет, что значение «truthy» (кнопка действительно нажата).
 *   2. Сбрасывает значение контрола обратно в false, чтобы кнопка была готова
 *      к следующему нажатию (wb-rules не делает это автоматически).
 *
 * Параметры:
 *   devName {string} — имя виртуального устройства.
 *   ctlName {string} — имя контрола-кнопки.
 *   v       {*}     — новое значение контрола.
 *
 * Возвращает: true, если нажатие валидно и обработано; false — иначе.
 * =============================================================================
 */
function onPush(devName, ctlName, v) {
    if (!v) return false;
    var p = devName + "/" + ctlName;
    try { if (dev[p] !== false) dev[p] = false; } catch (e) { }
    return true;
}

