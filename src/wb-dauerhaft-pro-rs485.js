/* =============================================================================
 * АНТИДРЕБЕЗГ КНОПОК УПРАВЛЕНИЯ (debounce)
 * =============================================================================
 * Фильтрует слишком быстрые повторные нажатия кнопок.
 * Если с момента последнего нажатия прошло менее 120 мс — возвращает true
 * (сигнал «игнорировать»).
 *
 * В v1.14 добавлен второй параметр devNameHint для надёжного определения
 * имени устройства. Единый диспетчер передаёт его явно из cellName/devName.
 * Без подсказки функция пытается извлечь имя, отрезая последний сегмент
 * после '_'. Это работает при простых именах, но ненадёжно при именах с '_'.
 *
 * Параметры:
 *   name        {string} — ключ вида NameBlind + "_" + суффикс (уникален для кнопки).
 *   devNameHint {string} — (необязательно) явное имя устройства для updateActivity.
 *
 * Возвращает: true если нажатие нужно игнорировать (дребезг), false — нажатие валидно.
 * =============================================================================
 */
function debounce(name, devNameHint) {
    var t = now();
    if (lastBtnTs[name] && (t - lastBtnTs[name] < 120)) return true;
    lastBtnTs[name] = t;
    var devName = devNameHint;
    if (!devName) {
        // Запасной вариант: отрезаем последний сегмент после '_'.
        // Работает корректно, если имя устройства не содержит '_'.
        var idx = name.lastIndexOf('_');
        devName = (idx > 0) ? name.substring(0, idx) : name;
    }
    DRIVER_REGISTRY.updateActivity(devName);
    return false;
}

/* =============================================================================
 * ВЫЧИСЛЕНИЕ CRC16 ДЛЯ ПРОТОКОЛА MODBUS RTU (crc16Modbus)
 * =============================================================================
 * Вычисляет контрольную сумму CRC16/Modbus для массива байт.
 * Алгоритм: CRC16 с полиномом 0xA001 (перевёрнутый 0x8005), начальное
 * значение 0xFFFF. Описан в разделе 5 протокола «Профкарниз Dauerhaft PRO
 * RS-485 v2.3».
 *
 * Параметры:
 *   buffer {Array<number>} — массив байт (числа 0–255).
 *
 * Возвращает: [crcLow, crcHigh] — массив из двух байт CRC16 (младший первым,
 *   согласно формату кадра Modbus RTU, раздел 2 протокола).
 * =============================================================================
 */
function crc16Modbus(buffer) {
    var crc = 0xFFFF;                     // начальное значение CRC
    for (var pos = 0; pos < buffer.length; pos++) {
        crc ^= buffer[pos];               // XOR со следующим байтом
        for (var i = 0; i < 8; i++) {     // обрабатываем каждый бит
            if ((crc & 0x0001) !== 0) {   // если младший бит = 1
                crc >>= 1;                // сдвиг вправо
                crc ^= 0xA001;            // XOR с полиномом (перевёрнутым)
            } else {                      // если младший бит = 0
                crc >>= 1;                // просто сдвиг
            }
        }
    }
    // Возвращаем массив: сначала младший байт, потом старший
    return [crc & 0xFF, (crc >> 8) & 0xFF];
}

/* =============================================================================
 * ПРЕОБРАЗОВАНИЕ МАССИВА БАЙТ В ШЕСТНАДЦАТЕРИЧНУЮ СТРОКУ (bytesToHexString)
 * =============================================================================
 * Параметры:
 *   arr {Array<number>} — массив байт (числа 0–255).
 * Возвращает: строку в верхнем регистре, например [0x01, 0xAB] → "01AB".
 * =============================================================================
 */
function bytesToHexString(arr) {
    var r = '';
    for (var i = 0; i < arr.length; i++) {
        var h = (arr[i] & 0xFF).toString(16);
        if (h.length < 2) h = '0' + h;
        r += h;
    }
    return r.toUpperCase();
}

/* =============================================================================
 * ПРЕОБРАЗОВАНИЕ ШЕСТНАДЦАТЕРИЧНОЙ СТРОКИ В МАССИВ БАЙТ (hexStringToBytes)
 * =============================================================================
 * Параметры:
 *   hex {string} — строка HEX-символов (должна иметь чётную длину).
 * Возвращает: Array<number> — массив байт.
 * =============================================================================
 */
function hexStringToBytes(hex) {
    var b = [];
    for (var i = 0; i < hex.length; i += 2) {
        b.push(parseInt(hex.substr(i, 2), 16));
    }
    return b;
}

/* =============================================================================
 * ИЗВЛЕЧЕНИЕ ОДНОГО БАЙТА ИЗ ШЕСТНАДЦАТЕРИЧНОЙ СТРОКИ ПО ПОЗИЦИИ (getByteAt)
 * =============================================================================
 * Позиция pos соответствует номеру байта (не символа): pos=0 → первые 2 символа.
 * Параметры:
 *   hexStr {string} — нормализованная HEX-строка (только [0-9a-fA-F]).
 *   pos    {number} — позиция байта (0-based).
 * Возвращает: число 0–255, или 0 при выходе за границы строки.
 * =============================================================================
 */
function getByteAt(hexStr, pos) {
    var s = pos * 2;                     // начальная позиция в строке для этого байта
    if (s + 2 > hexStr.length) return 0; // защита от выхода за границы строки
    return parseInt(hexStr.substr(s, 2), 16);
}

/* =============================================================================
 * БЫСТРАЯ ПРОВЕРКА CRC16 БЕЗ СОЗДАНИЯ МАССИВА БАЙТ (checkCrc16ModbusFast)
 * =============================================================================
 * Используется в горячем пути обработки ответов от приводов.
 * В отличие от checkCrc16Modbus() с hexStringToBytes(), считает CRC прямо
 * по HEX-строке и создаёт значительно меньше временных объектов.
 *
 * Алгоритм: тот же CRC16/Modbus, что и в crc16Modbus(), но входные данные
 * читаются посимвольно из HEX-строки без промежуточного массива байт.
 *
 * Параметры:
 *   hexStr {string} — нормализованная HEX-строка (только [0-9a-fA-F]),
 *                     включая 2 байта CRC в конце (минимум 5 байт = 10 символов).
 * Возвращает: true если CRC корректен, false иначе.
 * =============================================================================
 */
function checkCrc16ModbusFast(hexStr) {
    if (!hexStr || hexStr.length < 10 || (hexStr.length % 2) !== 0) return false;

    var dataChars = hexStr.length - 4;  // длина данных без последних 2 байт CRC
    var crc = 0xFFFF;

    for (var pos = 0; pos < dataChars; pos += 2) {
        var b = parseInt(hexStr.substr(pos, 2), 16);
        if (isNaN(b)) return false;

        crc ^= b;
        for (var i = 0; i < 8; i++) {
            if ((crc & 0x0001) !== 0) {
                crc >>= 1;
                crc ^= 0xA001;
            } else {
                crc >>= 1;
            }
        }
    }

    // Извлекаем переданные байты CRC (последние 4 символа строки)
    var crcLowGiven = parseInt(hexStr.substr(dataChars, 2), 16);
    var crcHighGiven = parseInt(hexStr.substr(dataChars + 2, 2), 16);

    return ((crc & 0xFF) === crcLowGiven) && (((crc >> 8) & 0xFF) === crcHighGiven);
}

/* =============================================================================
 * НОРМАЛИЗАЦИЯ ШЕСТНАДЦАТЕРИЧНОЙ СТРОКИ (normalizeHex)
 * =============================================================================
 * Удаляет все символы, не являющиеся HEX-цифрами, и приводит к нижнему регистру.
 * Используется для обработки ответов от wb-mqtt-serial, которые могут содержать
 * пробелы или другие символы.
 *
 * Параметры:
 *   str {string|*} — входная строка (любой тип, будет преобразован в строку).
 * Возвращает: строку из символов [0-9a-f].
 * =============================================================================
 */
function normalizeHex(str) {
    return String(str || '').replace(/[^0-9a-fA-F]/g, '').toLowerCase();
}

/* =============================================================================
 * ПРЕОБРАЗОВАНИЕ ЧИСЛА В ДВУХСИМВОЛЬНУЮ ШЕСТНАДЦАТЕРИЧНУЮ СТРОКУ (toHex2)
 * =============================================================================
 * Параметры:
 *   n {number} — число 0–255.
 * Возвращает: строку из двух символов в верхнем регистре, например 5 → "05", 255 → "FF".
 * =============================================================================
 */
function toHex2(n) {
    var h = (n & 0xFF).toString(16).toUpperCase();
    return (h.length < 2 ? '0' : '') + h;
}

/* =============================================================================
 * ФОРМИРОВАНИЕ СООБЩЕНИЯ ДЛЯ УПРАВЛЕНИЯ ПРИВОДОМ (blindRequestMsg)
 * =============================================================================
 * Собирает кадр запроса к приводу по протоколу «Профкарниз Dauerhaft PRO
 * RS-485 v2.3» (раздел 2 «Формат команды»):
 *   [адрес] [функция] [длина данных] [данные...] [CRC_L] [CRC_H]
 *
 * Важная особенность: функция 0x03 заменяется на 0x04.
 * В протоколе функция управления описана как 0x04 (раздел 3.4 «Управляющие
 * команды»). Внутри части кода функция передаётся как 0x03 по историческим
 * причинам, поэтому здесь выполняется явная замена для совместимости.
 *
 * Параметры:
 *   blindID     {number} — (не используется, зарезервировано).
 *   blindCh_L   {number} — Modbus-адрес устройства (1 байт).
 *   blindCh_H   {number} — (не используется, зарезервировано).
 *   commandBlind {number} — код функции (0x01, 0x02, 0x03→0x04, и т.д.).
 *   dataCode    {number} — первый байт данных (подкоманда).
 *   dataData    {number|Array|null} — дополнительные данные или null.
 *
 * Возвращает: HEX-строку кадра в верхнем регистре.
 * =============================================================================
 */
function blindRequestMsg(blindID, blindCh_L, blindCh_H, commandBlind, dataCode, dataData) {
    // Подмена 0x03 на 0x04 для совместимости с протоколом:
    // раздел 3.4 «Профкарниз Dauerhaft PRO RS-485 v2.3» описывает функцию 0x04.
    var func = (commandBlind === 0x03) ? 0x04 : commandBlind;

    // Формируем payload: всегда начинается с dataCode (подкоманда)
    var payload = [dataCode];

    // Добавляем дополнительные данные, если они есть
    if (dataData !== null && dataData !== undefined) {
        if (Object.prototype.toString.call(dataData) === '[object Array]') {
            payload = payload.concat(dataData);
        } else {
            payload.push(dataData);
        }
    }

    // Длина данных: количество байт в payload (1 байт)
    var len = payload.length & 0xFF;

    // Собираем кадр: [адрес, функция, длина] + payload
    var frame = [(blindCh_L & 0xFF), (func & 0xFF), len].concat(payload);

    // Вычисляем CRC16 по алгоритму Modbus RTU
    var crc = crc16Modbus(frame);

    // Добавляем CRC (младший байт первым, согласно разделу 2 протокола)
    frame = frame.concat(crc);

    // Возвращаем HEX-строку
    return bytesToHexString(frame);
}

/* =============================================================================
 * ПОСТРОЕНИЕ ПРОИЗВОЛЬНОГО MODBUS-КАДРА С CRC (makeFrame)
 * =============================================================================
 * Принимает массив байт (без CRC) и возвращает HEX-строку с добавленными
 * байтами CRC16/Modbus. Используется для команд с нестандартной структурой
 * (ping, адресные операции), которые не вписываются в формат blindRequestMsg().
 *
 * Параметры:
 *   bytes {Array<number>} — массив байт кадра без CRC.
 * Возвращает: HEX-строку кадра с CRC в верхнем регистре.
 * =============================================================================
 */
function makeFrame(bytes) {
    var crc = crc16Modbus(bytes);
    return bytesToHexString(bytes.concat(crc));
}

