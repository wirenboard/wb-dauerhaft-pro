/* =============================================================================
 * РЕЕСТР УСТРОЙСТВ ДРАЙВЕРА (DRIVER_REGISTRY)
 * =============================================================================
 * Централизованное хранилище метаданных о всех зарегистрированных устройствах,
 * а также методов для регистрации, обновления активности и очистки.
 * =============================================================================
 */
var DRIVER_REGISTRY = {
    // ----- ХРАНИЛИЩА РЕСУРСОВ -----

    /*
     * devices {object}
     * Ключ: NameBlind (строка).
     * Значение: объект с метаданными:
     *   name       {string}  — имя устройства
     *   created    {number}  — временная метка создания (мс)
     *   rules      {Array}   — имена правил wb-rules, созданных для устройства
     *   timers     {Array}   — имена таймеров, запущенных для устройства
     *   mqttSub    {*}       — дескриптор MQTT-подписки (возвращается trackMqttSafe)
     *   lastActive {number}  — временная метка последней активности (мс)
     *   data       {object}  — произвольные данные устройства (angleMode и др.)
     */
    devices: {},

    /*
     * rules {object}
     * Быстрый доступ к именам правил: ключ — имя правила, значение — true.
     * Используется при очистке устройства (cleanupDevice).
     */
    rules: {},

    /*
     * timers {object}
     * Аналогично rules, но для таймеров.
     */
    timers: {},

    /*
     * mqttSubscriptions {object}
     * Ключ: NameBlind. Значение: дескриптор MQTT-подписки.
     * Используется при очистке для отписки от MQTT.
     */
    mqttSubscriptions: {},

    /*
     * lastActivity {object}
     * Ключ: NameBlind. Значение: timestamp последней активности (мс).
     * Дублирует devices[name].lastActive для удобства обращения.
     */
    lastActivity: {},

    // ----- МЕТОДЫ РАБОТЫ С РЕЕСТРОМ -----

    /*
     * registerDevice(name)
     * Регистрирует новое устройство в реестре или возвращает существующую запись.
     * Параметры:
     *   name {string} — имя устройства.
     * Возвращает: объект устройства из this.devices[name].
     */
    registerDevice: function (name) {
        if (!this.devices[name]) {
            this.devices[name] = {
                name: name,
                created: now(),
                rules: [],           // будет заполняться именами правил
                timers: [],          // будет заполняться именами таймеров
                mqttSub: null,       // заполнится при создании MQTT‑подписки
                lastActive: now(),
                data: {}             // дополнительные данные (например, angleMode)
            };
        }
        return this.devices[name];
    },

    /*
     * updateActivity(name)
     * Обновляет временную метку последней активности устройства.
     * Вызывается при каждом ответе от привода, пользовательском действии
     * или отправке команды.
     * Параметры:
     *   name {string} — имя устройства.
     */
    updateActivity: function (name) {
        if (this.devices[name]) {
            var t = now();
            this.devices[name].lastActive = t;
            this.lastActivity[name] = t;
        }
    },

    /*
     * cleanupDevice(name)
     * Полностью удаляет устройство из реестра и освобождает все связанные ресурсы:
     *   - останавливает и удаляет все таймеры устройства
     *   - удаляет все правила wb-rules, созданные для устройства
     *     (фактически переопределяет их пустыми заглушками, т.к. wb-rules
     *     не предоставляет API удаления правил)
     *   - отписывается от MQTT-топика
     *   - очищает данные из глобальных объектов (posGuard, angleMode и т.д.)
     * Параметры:
     *   name {string} — имя устройства.
     * Возвращает: true если устройство было очищено, false если не найдено.
     */
    cleanupDevice: function (name) {
        var device = this.devices[name];
        if (!device) return false;

        log("Начинаем очистку устройства: " + name);
        var removed = 0;

        // Остановка и удаление таймеров
        for (var i = 0; i < device.timers.length; i++) {
            var timerName = device.timers[i];
            try {
                if (timers[timerName]) {
                    stopTicker(timerName);
                    delete this.timers[timerName];
                    removed++;
                }
            } catch (e) {
                log("Ошибка при остановке таймера " + timerName + ": " + e);
            }
        }

        // Удаление правил (фактически переопределение пустыми заглушками)
        for (var ri = 0; ri < device.rules.length; ri++) {
            var ruleName = device.rules[ri];
            try {
                if (typeof defineRule === 'function') {
                    defineRule(ruleName + "_gc", {
                        when: function () { return false; },
                        then: function () { }
                    });
                }
                delete this.rules[ruleName];
                removed++;
            } catch (e) {
                log("Ошибка при удалении правила " + ruleName + ": " + e);
            }
        }

        // Отписка от MQTT
        if (device.mqttSub && typeof untrackMqtt === 'function') {
            try {
                untrackMqtt(device.mqttSub);
                delete this.mqttSubscriptions[name];
                removed++;
            } catch (e) {
                log("Ошибка при удалении MQTT подписки: " + e);
            }
        }

        // Очистка данных из глобальных объектов
        this.cleanupDeviceData(name);

        device.cleaned = now();
        device.removedCount = removed;

        log("Очистка устройства " + name + " завершена, удалено элементов: " + removed);
        return true;
    },

    /*
     * cleanupDeviceData(name)
     * Удаляет записи об устройстве из всех глобальных объектов состояния.
     * Вызывается как при полной очистке (cleanupDevice), так и при
     * переинициализации устройства (в начале createBlind()).
     *
     * Параметры:
     *   name {string} — имя устройства.
     *
     * Примечание: поле 'globalMqttCallbacks' удалено в v1.14 (не используется).
     */
    cleanupDeviceData: function (name) {
        // Список глобальных объектов, в которых хранятся данные устройств.
        // Для каждого объекта удаляется запись с ключом = имя устройства.
        var dataFields = [
            'lastBtnTs', 'posGuard', 'angleGuard', 'lastRawPos',
            'busHoldUntil', 'blindAddr', 'lastReqAddr', 'angleFreezeUntil',
            'angleLastDeg', 'angleMode', 'onlineFlag',
            'lastSeenTs', 'pollState'
        ];

        for (var i = 0; i < dataFields.length; i++) {
            var field = dataFields[i];
            // Используем __root вместо window для совместимости с Duktape
            if (__root[field] && __root[field][name] !== undefined) {
                delete __root[field][name];
            }
        }

        if (this.devices[name]) {
            this.devices[name].data = {};
        }
    },


    /*
     * fullCleanup()
     * Принудительная очистка ВСЕХ зарегистрированных устройств.
     * Полезна при полном перезапуске драйвера или в диагностических целях.
     * Возвращает: количество успешно очищенных устройств.
     */
    fullCleanup: function () {
        log("Начинаем полную очистку драйвера...");
        var total = Object.keys(this.devices).length;
        var cleaned = 0;

        for (var deviceName in this.devices) {
            if (this.cleanupDevice(deviceName)) {
                cleaned++;
            }
        }

        log("Полная очистка завершена: " + cleaned + "/" + total + " устройств");
        return cleaned;
    }
};

