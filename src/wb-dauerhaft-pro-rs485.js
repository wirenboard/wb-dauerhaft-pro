/* =============================================================================
 * ПОСТРОЕНИЕ КАДРОВ ДЛЯ ГРУППОВОЙ УСТАНОВКИ ПОЗИЦИИ (buildGroupPositionFramesList)
 * =============================================================================
 * Формирует массив кадров установки позиции: по одному на каждый адрес.
 * Каждый кадр: команда 0x04/0x01/xx (позиция 0–100%).
 * Согласно разделу 3.4 протокола «Профкарниз Dauerhaft PRO RS-485 v2.3».
 *
 * Параметры:
 *   addrList {Array<number>} — массив числовых адресов приводов.
 *   _        {*}             — зарезервировано (имя виджета, не используется).
 *   percent  {number}        — позиция 0–100%.
 * Возвращает: Array<string> — массив HEX-строк кадров.
 * =============================================================================
 */
function buildGroupPositionFramesList(addrList, _, percent) {
    var p = Math.max(0, Math.min(100, percent | 0));
    var xx = (p <= 0) ? 0x00 : (p >= 100) ? 0x64 : p;
    var frames = [];
    for (var i = 0; i < addrList.length; i++) {
        var a = addrList[i] & 0xFF;
        frames.push(blindRequestMsg(0, a, 0, 0x03, 0x01, xx));
    }
    return frames;
}

/* =============================================================================
 * ПОСТРОЕНИЕ КАДРОВ ДЛЯ ГРУППОВОЙ УСТАНОВКИ УГЛА ЛАМЕЛЕЙ (buildGroupAngleFrames)
 * =============================================================================
 * Формирует массив кадров управления углом: по одному на каждый адрес.
 * Каждый кадр: команда 0x04/0x04/raw (угол в формате привода).
 * Согласно разделу 3.4 протокола «Профкарниз Dauerhaft PRO RS-485 v2.3».
 *
 * ВАЖНОЕ ОГРАНИЧЕНИЕ: групповая команда угла ВСЕГДА использует
 * compressed-диапазон (36–144), независимо от режима angleMode каждого
 * устройства. Это ограничение обусловлено тем, что перед отправкой
 * групповой команды неизвестно, какой режим использует каждый привод
 * из списка. Для однородных групп (все устройства одного типа) это
 * приемлемо. Для смешанных групп (compressed + direct) потребовался бы
 * предварительный опрос каждого устройства, что существенно усложнило бы
 * логику. Пользователь должен учитывать это при настройке.
 *
 * Параметры:
 *   addrList {Array<number>} — массив числовых адресов приводов.
 *   _        {*}             — зарезервировано (имя виджета, не используется).
 *   degUi    {number}        — угол 0–180° (пользовательский).
 * Возвращает: Array<string> — массив HEX-строк кадров.
 * =============================================================================
 */
function buildGroupAngleFrames(addrList, _, degUi) {
    // ОГРАНИЧЕНИЕ: групповая команда всегда использует compressed-диапазон (36–144).
    // Устройства с прямым отображением угла (direct-режим) могут получить
    // некорректное значение. Для однородных групп это приемлемо.
    // Исправление требует опроса angleMode каждого устройства перед отправкой.
    var d = Math.max(0, Math.min(180, degUi | 0));
    var raw = Math.round(36 + d * (144 - 36) / 180);
    if (raw < 36) raw = 36;
    if (raw > 144) raw = 144;
    var frames = [];
    for (var i = 0; i < addrList.length; i++) {
        var a = addrList[i] & 0xFF;
        frames.push(blindRequestMsg(0, a, 0, 0x03, 0x04, raw));
    }
    return frames;
}

