/* =============================================================================
 * ОЧЕРЕДЬ ОТПРАВКИ RS-485 / MQTT RPC (TX-ОЧЕРЕДЬ)
 * =============================================================================
 *
 * ЗАЧЕМ НУЖНА ОЧЕРЕДЬ
 * -------------------
 * RS-485 — полудуплексная шина. В один момент времени только одно устройство
 * может передавать данные. При одновременном появлении нескольких источников
 * команд (пользователь нажал кнопку, MAIN_POLL_TICKER отправляет опрос,
 * групповое управление) без очереди кадры перекрывали бы друг друга.
 *
 * СТРУКТУРА ОЧЕРЕДИ
 * -----------------
 * txQueueByPort — словарь: ключ = путь к порту, значение = массив элементов.
 * Каждый элемент очереди — объект с полями:
 *   port, speed, parity, stopBit  — параметры порта для RPC
 *   clientID                       — имя устройства (для MQTT-топика и логов)
 *   requestID                      — числовой ID запроса (определяет тип и приоритет)
 *   messageType                    — "HEX"
 *   message                        — HEX-строка кадра
 *   responseSize                   — ожидаемый размер ответа в байтах
 *   priority                       — TX_PRIO_* (чем меньше, тем важнее)
 *   seq                            — порядковый номер для стабильной сортировки
 *   createdAt                      — время постановки в очередь (мс)
 *   expireAt                       — время истечения TTL (мс)
 *   kind                           — строка-тег команды (для отладки и cancelTxItems)
 *   replaceKey                     — ключ для отмены предыдущих команд того же типа
 *   bypassPortHold                 — пропустить глобальную блокировку порта
 *
 * ОБРАБОТКА ОЧЕРЕДИ
 * -----------------
 * Очередь обслуживается двумя точками:
 *   1. enqueueTx() — вызывает pumpTxQueues() сразу после добавления команды.
 *   2. MAIN_POLL_TICKER — вызывает pumpTxQueues() каждые 250 мс.
 * Отдельный быстрый TX_QUEUE_TICKER не используется (устранён в v1.13).
 *
 * ПРИОРИТЕТЫ
 * ----------
 * TX_PRIO_STOP    = 0  — команда стоп: обгоняет всё остальное
 * TX_PRIO_CONTROL = 1  — пользовательское управление
 * TX_PRIO_CONFIG  = 2  — адресные операции, настройка пределов
 * TX_PRIO_POLL    = 3  — фоновый опрос (низший приоритет)
 *
 * TTL (время жизни)
 * -----------------
 * Каждая команда имеет expireAt. Если при попытке отправки время истекло,
 * команда выбрасывается. Опросы имеют короткий TTL (1800 мс): устаревший
 * опрос лучше пропустить, чем выполнить с запозданием.
 * =============================================================================
 */

