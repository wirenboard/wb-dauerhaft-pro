/* =============================================================================
 * БЕЗОПАСНАЯ УСТАНОВКА ЗНАЧЕНИЯ КОНТРОЛА (safeSet)
 * =============================================================================
 * Устанавливает значение контрола виртуального устройства через глобальный
 * объект dev[], только если новое значение отличается от текущего.
 *
 * Это важно для предотвращения избыточных срабатываний правил whenChanged:
 * wb-rules запускает правило только при реальном изменении значения, но
 * лишний вызов dev[path] = value всё равно создаёт нагрузку на движок.
 *
 * Параметры:
 *   ctrlPath {string} — путь контрола вида "ИмяУстройства/ИмяКонтрола".
 *   value    {*}      — новое значение.
 * =============================================================================
 */
function safeSet(ctrlPath, value) {
    try {
        // Устанавливаем новое значение только если оно действительно отличается
        // от текущего, чтобы избежать лишних операций и срабатываний правил.
        if (dev[ctrlPath] !== value) {
            dev[ctrlPath] = value;
        }
    } catch (e) {
        // Игнорируем любые ошибки — например, если контрол ещё не существует.
        // Это позволяет вызывать safeSet на ранних этапах инициализации,
        // не беспокоясь о порядке создания виджетов.
    }
}

/* =============================================================================
 * УСТАНОВКА СТАТУСА "ОНЛАЙН / ОФЛАЙН" ДЛЯ УСТРОЙСТВА (setOnline)
 * =============================================================================
 * Обновляет флаг онлайн/офлайн, контрол "Состояние" и сбрасывает inFlight-флаги
 * при потере связи (чтобы следующий тик не ждал ответа на зависший запрос).
 *
 * Параметры:
 *   NameBlind {string}  — имя устройства.
 *   on        {boolean} — true = онлайн, false = офлайн.
 * =============================================================================
 */
function setOnline(NameBlind, on) {
    if (on) {
        onlineFlag[NameBlind] = true;
        safeSet(NameBlind + '/Состояние', 'В СЕТИ');
        lastSeenTs[NameBlind] = now();
        DRIVER_REGISTRY.updateActivity(NameBlind);
    } else {
        onlineFlag[NameBlind] = false;
        safeSet(NameBlind + '/Состояние', 'НЕ В СЕТИ');
        // Сброс флагов inFlight при потере связи — иначе следующие опросы будут заблокированы
        if (pollState[NameBlind]) {
            pollState[NameBlind].ping.inFlight = false;
            pollState[NameBlind].pos.inFlight = false;
            pollState[NameBlind].angle.inFlight = false;
            pollState[NameBlind].sw.inFlight = false;
        }
    }
}

