/* =============================================================================
 * СОЗДАНИЕ ВИДЖЕТА ГРУППОВОГО УПРАВЛЕНИЯ ПРИВОДАМИ (createGroupWidget)
 * =============================================================================
 * Создаёт виртуальное устройство wb-rules для одновременного управления
 * несколькими приводами. Пользователь указывает список Modbus-адресов,
 * после чего кнопки и ползунки виджета управляют всеми приводами сразу.
 *
 * Архитектура:
 *   - Внутренние функции validateAndGetAddrs и startSeqSend замкнуты в
 *     createGroupWidget: они используют NameWidget и параметры порта.
 *   - Правила для кнопок и ползунков создаются через defineRule внутри
 *     createGroupWidget (в отличие от одиночных устройств, которые
 *     управляются единым диспетчером).
 *   - startSeqSend() использует baseId для формирования requestID:
 *     baseId=620 → TX_PRIO_STOP (групповой стоп), остальные → TX_PRIO_CONTROL.
 *
 * Параметры:
 *   NameWidget      {string} — имя виджета (отображается в интерфейсе).
 *   portBlind       {string} — путь к RS-485-порту.
 *   speedPortBlind  {number} — скорость порта в бод.
 *   parityBlind     {string} — паритет ("N").
 *   stopBitBlind    {number} — стоп-бит (1).
 * =============================================================================
 */
function createGroupWidget(NameWidget, portBlind, speedPortBlind, parityBlind, stopBitBlind) {

    // ----- 1. РЕГИСТРАЦИЯ В РЕЕСТРЕ -----
    var device = DRIVER_REGISTRY.registerDevice(NameWidget);
    // Инициализируем режим угла (будет определён при первом ответе)
    angleMode[NameWidget] = 'unknown';
    device.data.angleMode = 'unknown';

    // ----- 2. СОЗДАНИЕ ВИРТУАЛЬНОГО УСТРОЙСТВА -----
    if (getDevice(NameWidget) === undefined) {
        defineVirtualDevice(NameWidget, { title: NameWidget, cells: {} });
    }

    var vd = getDevice(NameWidget);

    // ----- 3. ДОБАВЛЕНИЕ КОНТРОЛОВ -----
    // Поля для задания списка адресов
    addControlSafe(vd, "Количество приводов",                  { type: 'value', value: 0, readonly: false });
    addControlSafe(vd, "Список адресов (HEX)",                 { type: 'text', value: '', readonly: false });
    addControlSafe(vd, "Адреса (HEX через пробел/запятую)",    { type: 'text', value: '' });
    addControlSafe(vd, "Статус адресов",                       { type: 'text', value: '' });

    // Кнопки группового управления
    addControlSafe(vd, "Группа открыть",  { type: 'pushbutton', readonly: false });
    addControlSafe(vd, "Группа стоп",     { type: 'pushbutton', readonly: false });
    addControlSafe(vd, "Группа закрыть",  { type: 'pushbutton', readonly: false });
    addControlSafe(vd, "Шаг вверх",       { type: 'pushbutton', readonly: false });
    addControlSafe(vd, "Шаг вниз",        { type: 'pushbutton', readonly: false });

    // Ползунки для групповой позиции и угла
    addControlSafe(vd, "Групповая позиция",     { type: 'range', value: 0, min: 0, max: 100, readonly: false });
    addControlSafe(vd, "Групповой угол ламели", { type: 'range', value: 0, min: 0, max: 180, readonly: false });

    /*
     * validateAndGetAddrs()
     * -----------------------------------------------------------------------
     * Внутренняя функция: валидирует список адресов из контролов виджета.
     * Приоритет: "Список адресов (HEX)" > "Адреса (HEX через пробел/запятую)".
     * Если задан "Количество приводов" > 0, он должен совпадать с числом адресов.
     * Результат валидации записывается в контрол "Статус адресов".
     *
     * Возвращает: массив числовых адресов или [] при ошибке.
     */
    function validateAndGetAddrs() {
        DRIVER_REGISTRY.updateActivity(NameWidget);
        var count      = Number(dev[NameWidget + "/Количество приводов"]) || 0;
        var rawPrimary = String(dev[NameWidget + "/Список адресов (HEX)"] || '');
        var rawSecondary = String(dev[NameWidget + "/Адреса (HEX через пробел/запятую)"] || '');
        var raw        = rawPrimary.trim() ? rawPrimary : rawSecondary;
        var parsed     = parseHexAddrList(raw);
        if (parsed.err) { dev[NameWidget + "/Статус адресов"] = parsed.err; return []; }
        if (count > 0 && parsed.list.length !== count) {
            dev[NameWidget + "/Статус адресов"] = "Количество ≠ списку (" + parsed.list.length + ")";
            return [];
        }
        dev[NameWidget + "/Статус адресов"] = "OK (" + parsed.list.length + ")";
        return parsed.list;
    }

    /*
     * startSeqSend(frames, baseId, repeats)
     * -----------------------------------------------------------------------
     * Постановка групповой последовательности кадров в TX-очередь.
     *
     * Несмотря на наличие в разделе 3.7 протокола «Профкарниз Dauerhaft PRO
     * RS-485 v2.3» возможности групповой команды одним кадром (функция 0x09),
     * групповое управление реализовано через очередь одиночных кадров для
     * максимальной совместимости с разными ревизиями прошивок приводов.
     *
     * Алгоритм:
     *   1. Отменяем все ожидающие groupSeq-команды этого виджета.
     *   2. Определяем приоритет: baseId=620 → TX_PRIO_STOP (групповой стоп).
     *   3. Для стопа сбрасываем txLastSentAt — немедленная отправка без TX_GAP.
     *   4. Для каждой итерации (repeats) кадры ротируются по кругу ((i+r)%len).
     *      Это гарантирует, что при повторных проходах порядок разный и один
     *      привод не оказывается постоянно последним в очереди.
     *
     * Параметры:
     *   frames  {Array<string>} — массив HEX-кадров для отправки.
     *   baseId  {number}        — базовый requestID для группы (определяет приоритет).
     *   repeats {number}        — количество повторов (стоп отправляется 3 раза).
     */
    function startSeqSend(frames, baseId, repeats) {
        if (!frames || !frames.length) return;
        if (!repeats || repeats < 1) repeats = 2;

        // Отменяем старые ожидающие групповые команды этого виджета
        cancelTxItems(function (item) {
            return item.clientID === NameWidget && item.kind === "groupSeq";
        });

        var priority = (baseId === 620) ? TX_PRIO_STOP : TX_PRIO_CONTROL;
        var t = now();
        var seq = 0;

        // Стоп должен уйти немедленно — сбрасываем интервал между кадрами
        if (priority === TX_PRIO_STOP) {
            txLastSentAt[portBlind] = 0;
        }

        for (var r = 0; r < repeats; r++) {
            for (var i = 0; i < frames.length; i++) {
                // Ротация: при r=1 первым уйдёт кадр с индексом 1, при r=2 — с индексом 2 и т.д.
                var idx = (i + r) % frames.length;
                enqueueTx({
                    port:         portBlind,
                    speed:        speedPortBlind,
                    parity:       parityBlind,
                    stopBit:      stopBitBlind,
                    clientID:     NameWidget,
                    requestID:    baseId + seq,
                    messageType:  "HEX",
                    message:      frames[idx],
                    responseSize: 0,          // групповые команды не ждут ответа
                    priority:     priority,
                    kind:         "groupSeq",
                    createdAt:    t + seq,    // незначительный сдвиг для сортировки
                    ttlMs:        (priority === TX_PRIO_STOP) ? 3000 : 10000,
                    bypassPortHold: priority === TX_PRIO_STOP
                });

                seq++;
            }
        }

        DRIVER_REGISTRY.updateActivity(NameWidget);

        //log("GROUP SEQ ENQUEUED total=" + (frames.length * repeats) +
            //" baseId=" + baseId +
            //" priority=" + priority);
    }

    // ----- 4. ПРАВИЛО ВАЛИДАЦИИ АДРЕСОВ ПРИ ИЗМЕНЕНИИ ПОЛЕЙ -----
    // Запускается автоматически при любом изменении полей адресов,
    // обновляя "Статус адресов" (OK или описание ошибки).
    var ruleAddrValidate = NameWidget + "_rule_addrValidate";
    defineRule(ruleAddrValidate, {
        whenChanged: [
            NameWidget + "/Количество приводов",
            NameWidget + "/Список адресов (HEX)",
            NameWidget + "/Адреса (HEX через пробел/запятую)"
        ],
        then: function () { validateAndGetAddrs(); }
    });
    device.rules.push(ruleAddrValidate);
    DRIVER_REGISTRY.rules[ruleAddrValidate] = true;

    // ----- 5. ПРАВИЛА ДЛЯ КНОПОК И ПОЛЗУНКОВ -----

    // Группа открыть (все приводы → 100%)
    var ruleGroupOpen = NameWidget + "_rule_groupOpen";
    defineRule(ruleGroupOpen, {
        whenChanged: NameWidget + "/Группа открыть",
        then: function (v) {
            if (!onPush(NameWidget, "Группа открыть", v)) return;
            var addrs = validateAndGetAddrs(); if (!addrs.length) return;
            var frames = buildGroupOpenFrames(addrs);
            startSeqSend(frames, 600, 1);  // baseId=600, 1 проход
        }
    });
    device.rules.push(ruleGroupOpen);
    DRIVER_REGISTRY.rules[ruleGroupOpen] = true;

    // Группа стоп (все приводы → стоп, 3 повтора для надёжности)
    var ruleGroupStop = NameWidget + "_rule_groupStop";
    defineRule(ruleGroupStop, {
        whenChanged: NameWidget + "/Группа стоп",
        then: function (v) {
            if (!onPush(NameWidget, "Группа стоп", v)) return;
            var addrs = validateAndGetAddrs(); if (!addrs.length) return;
            var frames = buildGroupStopFrames(addrs);
            startSeqSend(frames, 620, 3);  // baseId=620 → TX_PRIO_STOP, 3 прохода
        }
    });
    device.rules.push(ruleGroupStop);
    DRIVER_REGISTRY.rules[ruleGroupStop] = true;

    // Группа закрыть (все приводы → 0%)
    var ruleGroupClose = NameWidget + "_rule_groupClose";
    defineRule(ruleGroupClose, {
        whenChanged: NameWidget + "/Группа закрыть",
        then: function (v) {
            if (!onPush(NameWidget, "Группа закрыть", v)) return;
            var addrs = validateAndGetAddrs(); if (!addrs.length) return;
            var frames = buildGroupCloseFrames(addrs);
            startSeqSend(frames, 640, 1);  // baseId=640, 1 проход
        }
    });
    device.rules.push(ruleGroupClose);
    DRIVER_REGISTRY.rules[ruleGroupClose] = true;

    // Групповая позиция (ползунок 0–100%)
    var ruleGroupPos = NameWidget + "_rule_groupPos";
    defineRule(ruleGroupPos, {
        whenChanged: NameWidget + "/Групповая позиция",
        then: function () {
            var addrs = validateAndGetAddrs(); if (!addrs.length) return;
            var val = dev[NameWidget + "/Групповая позиция"] | 0;
            val = Math.max(0, Math.min(100, val));
            var frames = buildGroupPositionFramesList(addrs, NameWidget, val);
            startSeqSend(frames, 660, 1);  // baseId=660, 1 проход
        }
    });
    device.rules.push(ruleGroupPos);
    DRIVER_REGISTRY.rules[ruleGroupPos] = true;

    // Групповой угол ламели (ползунок 0–180°)
    // Примечание: всегда использует compressed-диапазон (36–144) — см. buildGroupAngleFrames.
    var ruleGroupAngle = NameWidget + "_rule_groupAngle";
    defineRule(ruleGroupAngle, {
        whenChanged: NameWidget + "/Групповой угол ламели",
        then: function () {
            var addrs = validateAndGetAddrs(); if (!addrs.length) return;
            var val = dev[NameWidget + "/Групповой угол ламели"] | 0;
            if (val < 0) val = 0; if (val > 180) val = 180;
            var frames = buildGroupAngleFrames(addrs, NameWidget, val);
            startSeqSend(frames, 680, 1);  // baseId=680, 1 проход
            // Защита от обратной связи (аналогично одиночному устройству)
            angleGuard[NameWidget] = (angleGuard[NameWidget] || 0) + 1;
            angleFreezeUntil[NameWidget] = now() + 1000;
        }
    });
    device.rules.push(ruleGroupAngle);
    DRIVER_REGISTRY.rules[ruleGroupAngle] = true;

    // Шаг вверх (групповой) — поворот ламелей вверх
    var ruleGroupStepUp = NameWidget + "_rule_groupStepUp";
    defineRule(ruleGroupStepUp, {
        whenChanged: NameWidget + "/Шаг вверх",
        then: function (v) {
            if (!onPush(NameWidget, "Шаг вверх", v)) return;
            var addrs = validateAndGetAddrs(); if (!addrs.length) return;
            var frames = buildGroupStepUpFrames(addrs);
            startSeqSend(frames, 700, 1);  // baseId=700, 1 проход
        }
    });
    device.rules.push(ruleGroupStepUp);
    DRIVER_REGISTRY.rules[ruleGroupStepUp] = true;

    // Шаг вниз (групповой) — поворот ламелей вниз
    var ruleGroupStepDown = NameWidget + "_rule_groupStepDown";
    defineRule(ruleGroupStepDown, {
        whenChanged: NameWidget + "/Шаг вниз",
        then: function (v) {
            if (!onPush(NameWidget, "Шаг вниз", v)) return;
            var addrs = validateAndGetAddrs(); if (!addrs.length) return;
            var frames = buildGroupStepDownFrames(addrs);
            startSeqSend(frames, 720, 1);  // baseId=720, 1 проход
        }
    });
    device.rules.push(ruleGroupStepDown);
    DRIVER_REGISTRY.rules[ruleGroupStepDown] = true;
}


/* =============================================================================
 * СОЗДАНИЕ ЭКЗЕМПЛЯРОВ УСТРОЙСТВ (ИНИЦИАЛИЗАЦИЯ ДРАЙВЕРА)
 * =============================================================================
 * Вызываем createBlind() для каждого привода и createGroupWidget() для
 * виджета группового управления. После этих вызовов singleDeviceTopics
 * заполнен и готов для регистрации единого диспетчера.
 *
 * Параметры createBlind: имя, порт, скорость, паритет, стоп-бит.
 * Адрес устройства задаётся позже в контроле "Смена адреса" / "Hex".
 * =============================================================================
 */

// Создаём виджеты для управления одиночными приводами
createBlind("Штора DauerhaftPRO",   "/dev/ttyRS485-2", 9600, "N", 1);
createBlind("Штора DauerhaftPRO 2", "/dev/ttyRS485-2", 9600, "N", 1);
createBlind("Штора DauerhaftPRO 3", "/dev/ttyRS485-2", 9600, "N", 1);

// Создаём виджет для группового управления несколькими приводами
createGroupWidget("Групповое управление", "/dev/ttyRS485-2", 9600, "N", 1);

/* =============================================================================
 * ЕДИНЫЙ ДИСПЕТЧЕР ОДИНОЧНЫХ УСТРОЙСТВ (dauerhaftpro_single_dispatcher)
 * =============================================================================
 *
 * НАЗНАЧЕНИЕ И ПРИНЦИП РАБОТЫ
 * ----------------------------
 * В v1.13 каждый вызов createBlind() создавал ≈17 правил wb-rules через
 * defineRule (по одному на каждый контрол устройства). При 3 устройствах —
 * это 51 правило. В v1.14 все контролы всех устройств обслуживаются
 * одним правилом с whenChanged по объединённому списку singleDeviceTopics.
 *
 * Преимущества единого диспетчера:
 *   - Значительно меньше объектов в heap wb-rules.
 *   - Проще hot-reload: одно правило вместо 51.
 *   - Проще добавление новых устройств: только createBlind() без изменений
 *     в логике правил.
 *
 * ВАЖНО: сигнатура then в wb-rules:
 *   function(newValue, devName, cellName)
 *   - newValue  — новое значение изменившегося контрола
 *   - devName   — имя виртуального устройства (без слэша)
 *   - cellName  — имя контрола (без слэша)
 * Передаём все три аргумента в _dp_dispatchSingleDevice().
 *
 * Диспетчер регистрируется ОДИН РАЗ в IIFE после всех createBlind(),
 * когда singleDeviceTopics полностью заполнен.
 *
 * Верификация сигнатуры then: проверяем, что аргумент devName
 * соответствует одному из зарегистрированных устройств через devicePortParams,
 * что неявно обеспечивает корректность диспетчеризации.
 * =============================================================================
 */
(function() {
    // Защита: если по какой-то причине список пуст, не регистрируем правило
    if (!singleDeviceTopics || !singleDeviceTopics.length) {
        log("WARN dauerhaftpro_single_dispatcher: нет топиков для подписки");
        return;
    }

    defineRule("dauerhaftpro_single_dispatcher", {
        // whenChanged: массив всех контролов всех одиночных устройств.
        // wb-rules вызывает then при изменении любого из них, передавая
        // (newValue, devName, cellName) — имя устройства и контрола раздельно.
        whenChanged: singleDeviceTopics,
        then: function (newValue, devName, cellName) {
            // Стандартная сигнатура wb-rules: (newValue, devName, cellName).
            // devName и cellName приходят раздельно — без конкатенации со слэшем.
            // Передаём в именованную функцию (не замыкание).
            _dp_dispatchSingleDevice(newValue, devName, cellName);
        }
    });

    log("dauerhaftpro_single_dispatcher: зарегистрирован, топиков=" + singleDeviceTopics.length);
}());
